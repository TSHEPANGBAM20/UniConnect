package com.mklt.uniconnect.Services;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;

import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.http.ContentDisposition;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;

import com.mklt.uniconnect.Entities.Project;
import com.mklt.uniconnect.Entities.ProjectFile;
import com.mklt.uniconnect.Entities.Student;
import com.mklt.uniconnect.Helpers.ProjectFileDto;
import com.mklt.uniconnect.Helpers.ProjectMembers;
import com.mklt.uniconnect.Helpers.ProjectRoles;
import com.mklt.uniconnect.Repositories.ProjectFileRepo;
import com.mklt.uniconnect.Repositories.ProjectMembersRepo;
import com.mklt.uniconnect.Repositories.ProjectsRepo;
import com.mklt.uniconnect.Repositories.StudentRepo;

// Everything to do with files that belong to a project: list, upload, download, delete.
@Service
public class ProjectFileServices {

    // The app enforces the same limits, but the server must not rely on that.
    private static final long MAX_BYTES = 10L * 1024 * 1024; // 10 MB
    private static final int MAX_NAME_LENGTH = 150;
    private static final Set<String> ALLOWED_EXTENSIONS = Set.of(
            "pdf", "doc", "docx", "ppt", "pptx", "xls", "xlsx", "txt", "zip", "png", "jpg", "jpeg");

    // uploads/projects/{projectId}/{storedName}
    private static final Path BASE_DIR = Paths.get("uploads", "projects");

    private final ProjectFileRepo projectFileRepo;
    private final ProjectsRepo projectsRepo;
    private final ProjectMembersRepo projectMembersRepo;
    private final StudentRepo studentRepo;

    public ProjectFileServices(ProjectFileRepo projectFileRepo, ProjectsRepo projectsRepo,
                               ProjectMembersRepo projectMembersRepo, StudentRepo studentRepo) {
        this.projectFileRepo = projectFileRepo;
        this.projectsRepo = projectsRepo;
        this.projectMembersRepo = projectMembersRepo;
        this.studentRepo = studentRepo;
    }

    // ---------- list ----------

    public List<ProjectFileDto> listFiles(Long projectId, Long studentId) {
        Project project = findProject(projectId);
        requireMember(findStudent(studentId), project);

        return projectFileRepo.findAllByProjectOrderByUploadedAtDesc(project)
                .stream()
                .map(ProjectFileDto::from)
                .toList();
    }

    // ---------- upload ----------

    @Transactional(rollbackFor = Exception.class)
    public ProjectFileDto uploadFile(Long projectId, Long studentId, MultipartFile upload) throws IOException {
        Project project = findProject(projectId);
        Student student = findStudent(studentId);
        requireMember(student, project);

        if (upload == null || upload.isEmpty()) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Choose a file to upload.");
        }
        if (upload.getSize() > MAX_BYTES) {
            throw new ResponseStatusException(HttpStatus.PAYLOAD_TOO_LARGE, "That file is too big. The limit is 10 MB.");
        }

        // The name comes from the client, so clean it and check the type before using it.
        String cleanName = cleanFileName(upload.getOriginalFilename());
        String extension = extensionOf(cleanName);
        if (!ALLOWED_EXTENSIONS.contains(extension)) {
            throw new ResponseStatusException(HttpStatus.UNSUPPORTED_MEDIA_TYPE,
                    "That file type isn't allowed. Use a PDF, Word, Excel, PowerPoint, text, zip or picture file.");
        }
        String displayName = shorten(cleanName, extension);

        // The name on disk is generated by us, so two uploads can never overwrite each other
        // and the client can never choose a path.
        String storedName = UUID.randomUUID() + "." + extension;
        Path directory = BASE_DIR.resolve(projectId.toString());
        Files.createDirectories(directory);
        Path target = directory.resolve(storedName);

        try {
            try (InputStream in = upload.getInputStream()) {
                Files.copy(in, target, StandardCopyOption.REPLACE_EXISTING);
            }

            String contentType = upload.getContentType() == null
                    ? MediaType.APPLICATION_OCTET_STREAM_VALUE
                    : upload.getContentType();

            ProjectFile saved = projectFileRepo.save(new ProjectFile(
                    project, displayName, storedName, contentType, upload.getSize(), student, LocalDateTime.now()));

            // keep the project's "latest file" name in step (shown on the Project Details page)
            project.setProjectFile(displayName);
            projectsRepo.save(project);

            return ProjectFileDto.from(saved);
        } catch (IOException | RuntimeException e) {
            Files.deleteIfExists(target); // don't leave a file on disk that the database doesn't know about
            throw e;
        }
    }

    // ---------- download ----------

    public ResponseEntity<Resource> downloadFile(Long projectId, Long fileId, Long studentId) {
        Project project = findProject(projectId);
        requireMember(findStudent(studentId), project);
        ProjectFile file = findFileInProject(fileId, project);

        Path path = pathOnDisk(project, file);
        if (!Files.isRegularFile(path)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "File not found on server");
        }

        MediaType mediaType;
        try {
            mediaType = MediaType.parseMediaType(file.getContentType());
        } catch (RuntimeException e) {
            mediaType = MediaType.APPLICATION_OCTET_STREAM; // unknown or missing content type
        }

        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION,
                        ContentDisposition.attachment().filename(file.getFileName(), StandardCharsets.UTF_8).build().toString())
                .header("X-Content-Type-Options", "nosniff")
                .contentType(mediaType)
                .body(new FileSystemResource(path));
    }

    // ---------- delete ----------

    @Transactional(rollbackFor = Exception.class)
    public void deleteFile(Long projectId, Long fileId, Long requesterId) {
        Project project = findProject(projectId);
        Student requester = findStudent(requesterId);
        ProjectMembers membership = requireMember(requester, project);
        ProjectFile file = findFileInProject(fileId, project);

        boolean isLeader = membership.getRole() == ProjectRoles.LEADER;
        boolean isUploader = file.getUploadedBy() != null && file.getUploadedBy().getId().equals(requester.getId());
        if (!isLeader && !isUploader) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN,
                    "Only the person who uploaded this file or the Team Lead can delete it.");
        }

        projectFileRepo.delete(file);
        try {
            Files.deleteIfExists(pathOnDisk(project, file));
        } catch (IOException e) {
            // the database row is gone; a file we cannot remove from disk must not make the delete fail
        }

        // point the project's "latest file" name at the newest file that is left (or clear it)
        String latestName = projectFileRepo.findAllByProjectOrderByUploadedAtDesc(project)
                .stream()
                .filter(f -> !f.getId().equals(file.getId())) // in case the delete has not been flushed yet
                .map(ProjectFile::getFileName)
                .findFirst()
                .orElse(null);
        project.setProjectFile(latestName);
        projectsRepo.save(project);
    }

    // Called when a whole project is disbanded or deleted: removes its files and database rows.
    public void deleteAllForProject(Project project) {
        List<ProjectFile> files = projectFileRepo.findAllByProjectOrderByUploadedAtDesc(project);
        for (ProjectFile file : files) {
            try {
                Files.deleteIfExists(pathOnDisk(project, file));
            } catch (IOException e) {
                // a file we cannot delete must not stop the project from being removed
            }
        }
        projectFileRepo.deleteAll(files);

        try {
            Files.deleteIfExists(BASE_DIR.resolve(project.getID().toString())); // only succeeds if the folder is empty
        } catch (IOException e) {
            // folder not empty (old files from before this feature): leave it
        }
    }

    // ---------- helpers ----------

    private Project findProject(Long projectId) {
        return projectsRepo.findById(projectId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Project not found"));
    }

    private Student findStudent(Long studentId) {
        return studentRepo.findById(studentId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Student not found"));
    }

    // Only members of the project may see, upload, download or delete its files.
    private ProjectMembers requireMember(Student student, Project project) {
        ProjectMembers membership = projectMembersRepo.findByStudentAndProject(student, project);
        if (membership == null) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "You are not a member of this project.");
        }
        return membership;
    }

    // A file id from another project is treated as "not found", so ids cannot be guessed across projects.
    private ProjectFile findFileInProject(Long fileId, Project project) {
        ProjectFile file = projectFileRepo.findById(fileId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "File not found"));
        if (!file.getProject().getID().equals(project.getID())) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "File not found");
        }
        return file;
    }

    // The full path of a stored file. Refuses anything that would end up outside the uploads folder.
    private Path pathOnDisk(Project project, ProjectFile file) {
        Path root = BASE_DIR.toAbsolutePath().normalize();
        Path path = root.resolve(project.getID().toString()).resolve(file.getStoredName()).normalize();
        if (!path.startsWith(root)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "File not found on server");
        }
        return path;
    }

    // Keeps only the file name: drops any folders ("..\..\x.pdf" becomes "x.pdf") and control characters.
    private static String cleanFileName(String original) {
        if (original == null) return "";
        String name = original.replace('\\', '/');
        name = name.substring(name.lastIndexOf('/') + 1);
        return name.replaceAll("\\p{Cntrl}", "").trim();
    }

    private static String extensionOf(String name) {
        int dot = name.lastIndexOf('.');
        if (dot < 0 || dot == name.length() - 1) return "";
        return name.substring(dot + 1).toLowerCase(Locale.ROOT);
    }

    // Very long names are shortened, but the extension is kept.
    private static String shorten(String name, String extension) {
        if (name.length() <= MAX_NAME_LENGTH) return name;
        String suffix = "." + extension;
        return name.substring(0, MAX_NAME_LENGTH - suffix.length()) + suffix;
    }
}
