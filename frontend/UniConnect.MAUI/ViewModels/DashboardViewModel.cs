
using System.Collections.ObjectModel;
using System.ComponentModel;
using System.Diagnostics;
using System.Runtime.CompilerServices;
using UniConnect.MAUI.Models;
using UniConnect.MAUI.Services;

namespace UniConnect.MAUI.ViewModels
{
    public class DashboardViewModel : INotifyPropertyChanged
    {
        private readonly ApiService _apiService;
    //comment
        public ObservableCollection<ProjectModel> Projects { get; } = new();

        public ObservableCollection<NotificationModel> Notifications { get; } = new();

        public string WelcomeMessage =>
            $"Welcome Back, {_apiService.CurrentUserName ?? "User"} {_apiService.CurrentUserSurname ?? string.Empty}".TrimEnd();

        private bool _isBusy;

        public bool IsBusy
        {
            get => _isBusy;
            set
            {
                _isBusy = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(ShowEmptyProjects));
                OnPropertyChanged(nameof(ShowEmptyNotifications));
            }
        }

        private bool _hasProjects;

        public bool HasProjects
        {
            get => _hasProjects;
            set
            {
                _hasProjects = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(ShowEmptyProjects));
            }
        }

        public bool ShowEmptyProjects =>
            !HasProjects && !IsBusy;

        private bool _hasNotifications;

        public bool HasNotifications
        {
            get => _hasNotifications;
            set
            {
                _hasNotifications = value;
                OnPropertyChanged();
                OnPropertyChanged(nameof(ShowEmptyNotifications));
            }
        }

        public bool ShowEmptyNotifications =>
            !HasNotifications && !IsBusy;

        public DashboardViewModel(ApiService apiService)
        {
            _apiService = apiService;
        }

        // Loads projects and deadline notifications.
        public async Task LoadProjectsAsync()
        {
            IsBusy = true;

            OnPropertyChanged(nameof(WelcomeMessage));

            try
            {
                // Load the logged-in user's projects.
                try
                {
                    // BACKEND:
                    // GET projects belonging to the currently logged-in user.
                    // Each project should provide ProjectId and ProjectName.

                    var projects = await _apiService.GetProjectsAsync(
                        _apiService.CurrentUserId);

                    Projects.Clear();

                    foreach (var project in projects ?? new List<ProjectModel>())
                    {
                        Projects.Add(project);
                    }

                    HasProjects = Projects.Count > 0;
                }
                catch (Exception ex)
                {
                    Debug.WriteLine($"PROJECT LOADING ERROR: {ex.Message}");

                    Projects.Clear();
                    HasProjects = false;
                }

                // Load deadline notifications from the backend.
                await LoadDeadlineNotificationsAsync();
            }
            finally
            {
                IsBusy = false;
            }
        }

        // Loads deadline notifications generated by the backend.
        private async Task LoadDeadlineNotificationsAsync()
        {
            Notifications.Clear();
            HasNotifications = false;

            try
            {
                // BACKEND:
                // GET /tasks/notifications/{studentId}
                //
                // The backend generates notifications for:
                // 1. OVERDUE tasks.
                // 2. Tasks due TODAY.
                // 3. Tasks due TOMORROW.
                //
                // Tasks with status DONE are excluded by the backend.
                // Tasks with deadlines further away do not generate notifications.
                //
                // Expected response fields:
                // NotificationId
                // TaskId
                // Message
                // DueDate
                // IsRead
                // NotificationType

                if (_apiService.CurrentUserId <= 0)
                {
                    Debug.WriteLine(
                        "NOTIFICATION LOADING: No logged-in student ID.");

                    return;
                }

                var notifications =
                    await _apiService.GetNotificationsAsync();

                // Display the closest deadlines first.
                var sortedNotifications = (notifications ?? new List<NotificationModel>())
                    .OrderBy(n => n.DueDate)
                    .ToList();

                foreach (var notification in sortedNotifications)
                {
                    Notifications.Add(notification);
                }

                HasNotifications = Notifications.Count > 0;

                Debug.WriteLine(
                    $"DEADLINE NOTIFICATIONS: {Notifications.Count} retrieved from backend.");
            }
            catch (Exception ex)
            {
                Notifications.Clear();
                HasNotifications = false;

                Debug.WriteLine(
                    $"NOTIFICATION LOADING ERROR: {ex.Message}");
            }
        }

        // Loads temporary dashboard preview projects.
        public void LoadPreviewProjects()
        {
            IsBusy = true;

            try
            {
                Projects.Clear();
                Notifications.Clear();

                HasNotifications = false;

                // PREVIEW DATA:
                // These projects are temporary sample data.
                // They are not retrieved from the backend.

                Projects.Add(new ProjectModel
                {
                    ProjectId = 1,
                    ProjectName = "UniConnect",
                    ProjectDescription = "University team collaboration platform",
                    StartDate = new DateOnly(2026, 10, 1),
                    EndDate = new DateOnly(2026, 11, 30)
                });

                Projects.Add(new ProjectModel
                {
                    ProjectId = 2,
                    ProjectName = "Handy Market",
                    ProjectDescription = "Marketplace for local service providers",
                    StartDate = new DateOnly(2026, 9, 15),
                    EndDate = new DateOnly(2026, 12, 15),
                    ProjectStatus = "IN PROGRESS"
                });

                Projects.Add(new ProjectModel
                {
                    ProjectId = 3,
                    ProjectName = "Student Portal",
                    ProjectDescription = "A platform for student resources",
                    StartDate = new DateOnly(2026, 10, 5),
                    EndDate = new DateOnly(2026, 12, 1),
                    ProjectStatus = "IN PROGRESS"
                });

                HasProjects = Projects.Count > 0;
            }
            finally
            {
                IsBusy = false;
            }
        }

        protected void OnPropertyChanged(
            [CallerMemberName] string name = null)
        {
            PropertyChanged?.Invoke(
                this,
                new PropertyChangedEventArgs(name));
        }

        public event PropertyChangedEventHandler PropertyChanged;
    }
}
